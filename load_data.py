def load_organizations():
    """Загрузить ПОО из Excel файла"""
    print("🏫 Загрузка ПОО из Excel...")

    wb = openpyxl.load_workbook('zip/СПО критерии по Климову.xlsx')
    sheet = wb.active

    db = Database()
    count = 0

    for i, row in enumerate(sheet.iter_rows(values_only=True), 1):
        if i == 1:  # Пропустить заголовок
            continue

        name, url, criteria_text = row

        if not name or not url:
            continue

        # Парсим критерии
        criteria_list = parse_criteria_from_text(criteria_text)

        # Ищем логотип
        logo_path = None
        logo_filename = f"{name}.jpg"
        logo_filename_webp = f"{name}.webp"

        # Проверяем существование файла
        import os
        if os.path.exists(f"zip/Лого ПОО/{logo_filename}"):
            logo_path = f"zip/Лого ПОО/{logo_filename}"
        elif os.path.exists(f"zip/Лого ПОО/{logo_filename_webp}"):
            logo_path = f"zip/Лого ПОО/{logo_filename_webp}"

        db.add_organization(name, url, criteria_text, criteria_list, logo_path)
        count += 1
        print(f"  ✅ {name} - критерии: {', '.join(criteria_list)}")

    print(f"✅ Загружено {count} ПОО\n")

