# Карта для преобразования текстовых критериев в код
CRITERIA_MAP = {
    'человек-человек': 'Human',
    'человек-природа': 'Nature',
    'человек-техника': 'Tech',
    'человек-знаковые системы': 'Sign',
    'человек-знаковая система': 'Sign',
    'человек-художественный образ': 'Art',
    'человек-художественные образы': 'Art',
}

def parse_criteria_from_text(text):
    """Парсит критерии из текста и возвращает список кодов"""
    if not text:
        return []

    text = text.lower().strip()
    criteria_list = []

    # Разделить по запятой
    parts = [p.strip() for p in text.split(',')]

    for part in parts:
        if part in CRITERIA_MAP:
            code = CRITERIA_MAP[part]
            if code not in criteria_list:
                criteria_list.append(code)

    return criteria_list

